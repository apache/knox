package org.apache.knox.gateway.services.knoxidf.delegation;

import org.apache.knox.gateway.services.Service;
import org.apache.knox.gateway.services.ServiceLifecycleException;

import java.util.Optional;

/**
 * Gateway service that stores and evaluates RFC 8693 delegation policies for Knox IDF.
 */
public interface DelegationPolicyService extends Service {

  /**
   * Registers a new delegation policy. The registrationId is generated by the service.
   *
   * @throws ServiceLifecycleException if the actor (actorAuthority, actorId) is already registered
   *     or a storage error occurs
   */
  DelegationPolicy register(DelegationPolicy policy) throws ServiceLifecycleException;

  /**
   * Fully replaces all fields including child rows (users, groups, resource policy).
   * Child rows are deleted and re-inserted transactionally.
   *
   * @throws ServiceLifecycleException if no policy exists for registrationId, or a storage error occurs
   */
  void update(String registrationId, DelegationPolicy policy) throws ServiceLifecycleException;

  void delete(String registrationId);

  Optional<DelegationPolicy> get(String registrationId);

  /** Primary lookup used by evaluate() and by the admin API scope-limiting check. */
  Optional<DelegationPolicy> findByActor(String actorAuthority, String actorId);

  /** @param actorAuthorityFilter null returns all policies */
  DelegationPolicyList list(String actorAuthorityFilter);

  PolicyDecision evaluate(PolicyCheckRequest request);
}
